
%% Generate Project Benchmark Plots
% Compares LQR and Pure Pursuit under the baseline operating condition.

clearvars;
close all;
clc;

%% Set paths

matlabDir = fileparts(mfilename('fullpath'));
addpath(matlabDir);

outputDir = fullfile(matlabDir, 'results', 'plots');

if ~exist(outputDir, 'dir')
    mkdir(outputDir);
end

%% Simulation configuration

vx = 5.0;
initial_offset = 0.25;
mu = 0.4;

dt = 0.0003125;
controller_dt = 0.0025;

lookahead = 1.6;

fprintf('Running baseline LQR simulation...\n');

lqr_5 = simulate_lqr( ...
    vx, initial_offset, [], [], 5.0, false, ...
    mu, dt, controller_dt);

fprintf('\nRunning baseline Pure Pursuit simulation...\n');

pp_5 = simulate_lqr( ...
    vx, initial_offset, [], [], 5.0, false, ...
    mu, dt, controller_dt, ...
    'pure_pursuit', lookahead);

%% Plot 1: Vehicle trajectory comparison

fig1 = figure( ...
    'Color', 'w', ...
    'Position', [100, 100, 1500, 400]);

plot(lqr_5.x_ref, lqr_5.y_ref, ...
    'k--', 'LineWidth', 1.8);
hold on;

plot(lqr_5.X_pos, lqr_5.Y_pos, ...
    'b-', 'LineWidth', 1.8);

plot(pp_5.X_pos, pp_5.Y_pos, ...
    'r-', 'LineWidth', 1.8);

plot(lqr_5.X_pos(1), lqr_5.Y_pos(1), ...
    'ko', 'MarkerFaceColor', 'k', 'MarkerSize', 7);

plot(lqr_5.X_pos(end), lqr_5.Y_pos(end), ...
    'bs', 'MarkerFaceColor', 'b', 'MarkerSize', 7);

plot(pp_5.X_pos(end), pp_5.Y_pos(end), ...
    'rs', 'MarkerFaceColor', 'r', 'MarkerSize', 7);

xlabel('Longitudinal Position (m)');
ylabel('Lateral Position (m)');

title('Vehicle Path Tracking Comparison');

lgd1 = legend( ...
    'Reference Path', ...
    'LQR', ...
    'Pure Pursuit (1.6 m)', ...
    'Initial Position', ...
    'LQR Endpoint', ...
    'Pure Pursuit Endpoint', ...
    'Location', 'best');

set(lgd1, ...
    'Color', 'w', ...
    'EdgeColor', 'k', ...
    'TextColor', 'k', ...
    'Box', 'on');

xlim([0 50]);
ylim([-2.5 2.5]);

% Preserve equal physical scaling on both axes.
daspect([1 1 1]);
pbaspect([10 1 1]);

grid on;
box on;

% Apply consistent publication-style formatting.
set(fig1, 'Color', 'w');

axes_handles = findall(fig1, 'Type', 'axes');

set(axes_handles, ...
    'Color', 'w', ...
    'XColor', 'k', ...
    'YColor', 'k', ...
    'GridColor', [0.75 0.75 0.75], ...
    'FontName', 'Arial', ...
    'FontSize', 11, ...
    'LineWidth', 1);

text_handles = findall(fig1, 'Type', 'text');
set(text_handles, 'Color', 'k');

exportgraphics(fig1, ...
    fullfile(outputDir, 'trajectory_comparison.png'), ...
    'Resolution', 300);

savefig(fig1, ...
    fullfile(outputDir, 'trajectory_comparison.fig'));

%% Plot 2: Cross-track error comparison

fig2 = figure( ...
    'Color', 'w', ...
    'Position', [100, 100, 1000, 550]);

plot(lqr_5.t, lqr_5.ey_history, ...
    'b-', 'LineWidth', 1.6);
hold on;

plot(pp_5.t, pp_5.ey_history, ...
    'r-', 'LineWidth', 1.6);

yline(0.1, 'k--', '+0.1 m threshold', ...
    'LineWidth', 1.1);

yline(-0.1, 'k--', '-0.1 m threshold', ...
    'LineWidth', 1.1);

xline(2.0, 'Color', [0.4 0.4 0.4], ...
    'LineStyle', ':', ...
    'LineWidth', 1.2, ...
    'Label', 'Post-startup window');

xlabel('Time (s)');
ylabel('Cross-Track Error (m)');

title('Cross-Track Error Over Time');

lgd2 = legend( ...
    'LQR', ...
    'Pure Pursuit (1.6 m)', ...
    'Location', 'best');

set(lgd2, ...
    'Color', 'w', ...
    'EdgeColor', 'k', ...
    'TextColor', 'k', ...
    'Box', 'on');

grid on;
box on;

ylim([-0.3 0.3]);
yticks(-0.3:0.05:0.3);

% Apply consistent publication-style formatting.
set(fig2, 'Color', 'w');

axes_handles = findall(fig2, 'Type', 'axes');

set(axes_handles, ...
    'Color', 'w', ...
    'XColor', 'k', ...
    'YColor', 'k', ...
    'GridColor', [0.75 0.75 0.75], ...
    'FontName', 'Arial', ...
    'FontSize', 11, ...
    'LineWidth', 1);

text_handles = findall(fig2, 'Type', 'text');
set(text_handles, 'Color', 'k');

exportgraphics(fig2, ...
    fullfile(outputDir, 'cross_track_error.png'), ...
    'Resolution', 300);

savefig(fig2, ...
    fullfile(outputDir, 'cross_track_error.fig'));

%% Plot 3: Requested versus applied steering

fig3 = figure( ...
    'Color', 'w', ...
    'Position', [100, 100, 1000, 750]);

tiledlayout(2, 1, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

% LQR steering
nexttile;

plot(lqr_5.t_control, ...
    rad2deg(lqr_5.delta_command_history), ...
    'b--', 'LineWidth', 1.3);
hold on;

plot(lqr_5.t_control, ...
    rad2deg(lqr_5.delta_history), ...
    'b-', 'LineWidth', 1.6);

yline(rad2deg(0.5), 'k:', '+28.65 deg limit');
yline(rad2deg(-0.5), 'k:', '-28.65 deg limit');

ylabel('Steering Angle (deg)');
title('LQR Steering Commands');

lgd3a = legend( ...
    'Requested', ...
    'Applied', ...
    'Location', 'best');

set(lgd3a, ...
    'Color', 'w', ...
    'EdgeColor', 'k', ...
    'TextColor', 'k', ...
    'Box', 'on');

grid on;
box on;

ylim([-100 100]);
yticks(-100:25:100);

% Pure Pursuit steering
nexttile;

plot(pp_5.t_control, ...
    rad2deg(pp_5.delta_command_history), ...
    'r--', 'LineWidth', 1.3);
hold on;

plot(pp_5.t_control, ...
    rad2deg(pp_5.delta_history), ...
    'r-', 'LineWidth', 1.6);

yline(rad2deg(0.5), 'k:', '+28.65 deg limit');
yline(rad2deg(-0.5), 'k:', '-28.65 deg limit');

xlabel('Time (s)');
ylabel('Steering Angle (deg)');
title('Pure Pursuit Steering Commands');

lgd3b = legend( ...
    'Requested', ...
    'Applied', ...
    'Location', 'best');

set(lgd3b, ...
    'Color', 'w', ...
    'EdgeColor', 'k', ...
    'TextColor', 'k', ...
    'Box', 'on');

grid on;
box on;

ylim([-30 30]);
yticks(-30:10:30);

% Apply consistent publication-style formatting.
set(fig3, 'Color', 'w');

axes_handles = findall(fig3, 'Type', 'axes');

set(axes_handles, ...
    'Color', 'w', ...
    'XColor', 'k', ...
    'YColor', 'k', ...
    'GridColor', [0.75 0.75 0.75], ...
    'FontName', 'Arial', ...
    'FontSize', 11, ...
    'LineWidth', 1);

text_handles = findall(fig3, 'Type', 'text');
set(text_handles, 'Color', 'k');

exportgraphics(fig3, ...
    fullfile(outputDir, 'steering_comparison.png'), ...
    'Resolution', 300);

savefig(fig3, ...
    fullfile(outputDir, 'steering_comparison.fig'));

%% Save underlying simulation data

save( ...
    fullfile(outputDir, 'baseline_plot_data.mat'), ...
    'lqr_5', 'pp_5');

%% Print output location and summary

fprintf('\n====================================\n');
fprintf('PROJECT PLOTS GENERATED SUCCESSFULLY\n');
fprintf('====================================\n');

fprintf('Output directory:\n%s\n\n', outputDir);

fprintf('LQR overall RMS CTE: %.5f m\n', ...
    lqr_5.rms_cross_track_m);

fprintf('Pure Pursuit overall RMS CTE: %.5f m\n', ...
    pp_5.rms_cross_track_m);

fprintf('LQR settling time: %.3f s\n', ...
    lqr_5.settling_time_s);

fprintf('Pure Pursuit settling time: %.3f s\n', ...
    pp_5.settling_time_s);

fprintf('\nGenerated files:\n');
fprintf('  trajectory_comparison.png\n');
fprintf('  trajectory_comparison.fig\n');
fprintf('  cross_track_error.png\n');
fprintf('  cross_track_error.fig\n');
fprintf('  steering_comparison.png\n');
fprintf('  steering_comparison.fig\n');
fprintf('  baseline_plot_data.mat\n');
